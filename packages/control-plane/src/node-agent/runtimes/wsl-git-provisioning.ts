import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import type { ExecutorContext } from "./contracts.ts";
import { workspaceGitEnvironmentEntries } from "./docker.ts";
import { WSL_BOOTSTRAP_ROOT, WSL_DEFAULT_WORKSPACE } from "./wsl-lifecycle.ts";

/**
 * WSL 工作区 Git 供给（openspec change add-wsl-runtime，Phase 6.1/6.2）。
 *
 * 复用既有 managed Git workspace provisioning 的语义（ref/depth/submodule/LFS/subdirectory
 * 与凭证处理）：Node Agent 把 managed 凭证桥接进 distro 的 `/run/task-handoff/git-auth`，
 * 在 distro 内以与 Docker 同构的 clone 流程物化工作区。凭证、临时 token 与 secret 只存在于
 * distro 临时目录与 Node Agent 进程内，MUST NOT 落入模板、公共协议或日志。
 */

export const WSL_GIT_AUTH_DIR = "/run/task-handoff/git-auth";
export const WSL_GIT_RUNTIME_DIR = "/run/task-handoff/git-runtime";
export const WSL_GIT_PROVISION_SCRIPT = `${WSL_BOOTSTRAP_ROOT}/git-wsl-provision.sh`;
export const WSL_GIT_CREDENTIAL_HELPER = `${WSL_BOOTSTRAP_ROOT}/git-wsl-credential-helper.mjs`;
export const WSL_GIT_PROVISION_STAGE_PREFIX = "TASK_HANDOFF_GIT_PROVISIONING_STAGE=";
export const WSL_GIT_PROVISION_ERROR_PREFIX = "TASK_HANDOFF_GIT_PROVISIONING_ERROR=";
export const WSL_GIT_PROVISION_COMMIT_PREFIX = "TASK_HANDOFF_GIT_PROVISIONING_COMMIT=";

export type WslGitExecutor = {
  execOrThrow(name: string, argv: readonly string[], options?: Record<string, unknown>): Promise<{ stdout: string; stderr: string; exitCode: number }>;
  execStream(name: string, argv: readonly string[], options?: Record<string, unknown>): Promise<{ stdout: string; stderr: string; exitCode: number }>;
  copyIntoDistro(name: string, sourcePath: string, destinationPath: string, options?: Record<string, unknown>): Promise<unknown>;
};

export function buildWslGitCredentialHelperScript() {
  return `#!/usr/bin/env node
// Generated by the Task Handoff node agent. Reads bridged managed credentials and
// implements the git credential helper contract for HTTPS remotes only. SSH is
// handled by GIT_SSH_COMMAND with the bridged private key, so this helper never
// emits secrets on stdout except the username/password git itself requires.
import fs from "node:fs";
import path from "node:path";
const runtimeDir = process.env.TASK_HANDOFF_WSL_GIT_RUNTIME_DIR || ${JSON.stringify(WSL_GIT_RUNTIME_DIR)};
const mode = process.argv[2];
if (mode !== "credential") process.exit(0);
let input = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (chunk) => { input += chunk; });
process.stdin.on("end", () => {
  const fields = {};
  for (const line of input.split(/\\r?\\n/)) {
    const index = line.indexOf("=");
    if (index > 0) fields[line.slice(0, index)] = line.slice(index + 1);
  }
  if (fields.protocol && fields.protocol !== "https") process.exit(0);
  let entries = [];
  try { entries = fs.readdirSync(runtimeDir).filter((name) => name.startsWith("credential-")); } catch { process.exit(0); }
  for (const name of entries.sort()) {
    const dir = path.join(runtimeDir, name);
    let scope = {};
    try { scope = JSON.parse(fs.readFileSync(path.join(dir, "scope.json"), "utf8")); } catch {}
    if (scope.scheme && scope.scheme !== "https") continue;
    if (fields.host && scope.host && scope.host !== fields.host) continue;
    let username = "";
    let token = "";
    try { username = fs.readFileSync(path.join(dir, "username"), "utf8").trim(); } catch {}
    try { token = fs.readFileSync(path.join(dir, "token"), "utf8").trim(); } catch {}
    if (!token) continue;
    process.stdout.write("username=" + username + "\\npassword=" + token + "\\n");
    process.exit(0);
  }
  process.exit(1);
});
`;
}

export function buildWslGitProvisionScript() {
  return `#!/usr/bin/env bash
set -euo pipefail

# Cross-filesystem normalization (6.4): drvfs mounts and the distro ext4 root can disagree on
# default modes, so pin the provisioning umask and hand the materialized workspace to the template's
# \`agent\` user when it exists.
umask 022

workspace="\${TASK_HANDOFF_WORKSPACE:-${WSL_DEFAULT_WORKSPACE}}"
staging="\${workspace}/.task-handoff-git-provisioning"
checkout="\${staging}/checkout"
runtime_dir="${WSL_GIT_RUNTIME_DIR}"

fail() {
  printf '${WSL_GIT_PROVISION_ERROR_PREFIX}%s\\n' "$1" >&2
  exit "\${2:-1}"
}
stage() {
  printf '${WSL_GIT_PROVISION_STAGE_PREFIX}%s\\n' "$1"
}

mkdir -p "\${workspace}" "\${staging}" "\${runtime_dir}"
existing="$(find "\${workspace}" -mindepth 1 -maxdepth 1 ! -name .task-handoff-git-provisioning -print -quit 2>/dev/null)"
if [ -n "\${existing}" ]; then
  if [ -e "\${workspace}/.git" ]; then
    echo "Workspace is already materialized; skipping provisioning."
    exit 0
  fi
  fail WORKSPACE_NOT_EMPTY 73
fi
rm -rf -- "\${staging}"
mkdir -p "\${staging}"

if [ -d "${WSL_GIT_AUTH_DIR}" ]; then
  cp -a "${WSL_GIT_AUTH_DIR}/." "\${runtime_dir}/"
fi
chmod 0700 "\${runtime_dir}"

export TASK_HANDOFF_WSL_GIT_RUNTIME_DIR="\${runtime_dir}"
export GIT_TERMINAL_PROMPT=0
git_config=(-c credential.helper= -c credential.helper="!node ${WSL_GIT_CREDENTIAL_HELPER} credential" -c credential.useHttpPath=true)

ssh_command=""
for credential_dir in "\${runtime_dir}"/credential-*; do
  [ -d "\${credential_dir}" ] || continue
  if [ -f "\${credential_dir}/private-key" ]; then
    chmod 0600 "\${credential_dir}/private-key"
    known_hosts="\${credential_dir}/known_hosts"
    [ -f "\${known_hosts}" ] || : > "\${known_hosts}"
    ssh_command="ssh -i \${credential_dir}/private-key -o IdentitiesOnly=yes -o UserKnownHostsFile=\${known_hosts} -o StrictHostKeyChecking=yes"
  fi
done
export GIT_SSH_COMMAND="\${ssh_command}"

clone_args=(clone --progress)
if [ -n "\${TASK_HANDOFF_WORKSPACE_GIT_DEPTH:-}" ] && [ -z "\${TASK_HANDOFF_WORKSPACE_GIT_COMMIT:-}" ]; then clone_args+=(--depth "\${TASK_HANDOFF_WORKSPACE_GIT_DEPTH}"); fi
if [ -n "\${TASK_HANDOFF_WORKSPACE_GIT_REF:-}" ]; then clone_args+=(--branch "\${TASK_HANDOFF_WORKSPACE_GIT_REF}"); fi
clone_args+=(-- "\${TASK_HANDOFF_WORKSPACE_GIT_URL}" "\${checkout}")

stage cloning
if ! git "\${git_config[@]}" "\${clone_args[@]}"; then fail CLONE_FAILED 74; fi

if [ -n "\${TASK_HANDOFF_WORKSPACE_GIT_COMMIT:-}" ]; then
  stage checking-out
  if ! git -C "\${checkout}" checkout --detach "\${TASK_HANDOFF_WORKSPACE_GIT_COMMIT}"; then fail REF_NOT_FOUND 75; fi
fi
if [ "\${TASK_HANDOFF_WORKSPACE_GIT_SUBMODULES:-false}" = "true" ]; then
  stage submodules
  if ! git "\${git_config[@]}" -C "\${checkout}" submodule update --init --recursive --progress; then fail CLONE_FAILED 74; fi
fi
if [ "\${TASK_HANDOFF_WORKSPACE_GIT_LFS:-false}" = "true" ]; then
  stage lfs
  if ! git "\${git_config[@]}" -C "\${checkout}" lfs pull; then fail LFS_FAILED 76; fi
fi
if [ -n "\${TASK_HANDOFF_WORKSPACE_SUBDIRECTORY:-}" ] && [ ! -d "\${checkout}/\${TASK_HANDOFF_WORKSPACE_SUBDIRECTORY}" ]; then
  fail SUBDIRECTORY_NOT_FOUND 75
fi
stage finalizing
printf '${WSL_GIT_PROVISION_COMMIT_PREFIX}%s\\n' "$(git -C "\${checkout}" rev-parse HEAD 2>/dev/null || true)"
shopt -s dotglob nullglob
mv -- "\${checkout}"/* "\${workspace}/"
rm -rf -- "\${staging}"
if id agent >/dev/null 2>&1; then chown -R agent:agent "\${workspace}" 2>/dev/null || true; fi
`;
}

export type WslGitProvisionResult = {
  commit?: string;
  stages: string[];
};

export type WslGitWorkspaceProvisionerOptions = {
  executor: WslGitExecutor;
  logger?: (message: string, data: Record<string, unknown>) => void;
};

function parseMarker(output: string, prefix: string) {
  const value = output
    .split(/\r?\n/)
    .filter((line) => line.startsWith(prefix))
    .map((line) => line.slice(prefix.length).trim())
    .filter(Boolean)
    .pop();
  return value;
}

export class WslGitWorkspaceProvisioner {
  private readonly executor: WslGitExecutor;
  private readonly logger?: (message: string, data: Record<string, unknown>) => void;

  constructor(options: WslGitWorkspaceProvisionerOptions) {
    this.executor = options.executor;
    this.logger = options.logger;
  }

  /** 桥接 Node Agent 侧 bootstrap 辅助脚本（凭证 helper 与供给脚本）。 */
  async ensureScripts(distroName: string) {
    const directory = fs.mkdtempSync(path.join(os.tmpdir(), "task-handoff-wsl-git-"));
    try {
      const provisionScript = path.join(directory, "git-wsl-provision.sh");
      const helperScript = path.join(directory, "git-wsl-credential-helper.mjs");
      fs.writeFileSync(provisionScript, buildWslGitProvisionScript(), { mode: 0o755 });
      fs.writeFileSync(helperScript, buildWslGitCredentialHelperScript(), { mode: 0o600 });
      await this.executor.execOrThrow(distroName, ["sh", "-c", `mkdir -p ${WSL_BOOTSTRAP_ROOT}`]);
      await this.executor.copyIntoDistro(distroName, provisionScript, WSL_GIT_PROVISION_SCRIPT);
      await this.executor.copyIntoDistro(distroName, helperScript, WSL_GIT_CREDENTIAL_HELPER);
      await this.executor.execOrThrow(distroName, ["sh", "-c", `chmod 0755 ${WSL_GIT_PROVISION_SCRIPT} && chmod 0600 ${WSL_GIT_CREDENTIAL_HELPER}`]);
    } finally {
      fs.rmSync(directory, { recursive: true, force: true });
    }
  }

  async provision(
    context: ExecutorContext,
    distroName: string,
    options: { onOutput?: (data: string) => void; signal?: AbortSignal; timeoutMs?: number } = {},
  ): Promise<WslGitProvisionResult> {
    const input = context.gitWorkspaceProvisioning;
    if (!input || context.project.source.type === "local-folder") {
      throw Object.assign(new Error("Git provisioning requires a Git source and operation input."), { code: "GIT_WORKSPACE_PROVISIONING_INVALID", statusCode: 400 });
    }
    await this.ensureScripts(distroName);
    const authDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "task-handoff-wsl-git-auth-"));
    fs.chmodSync(authDirectory, 0o700);
    try {
      this.materializeGitProvisioningAuth(authDirectory, input);
      await this.bridgeAuth(distroName, authDirectory);
      const environment = this.gitEnvironment(context);
      // 用 env 前缀把 Git 契约参数显式声明进 distro 命令，避免继承任何模板/镜像元数据。
      const command = [
        ...Object.entries(environment).map(([key, value]) => `${key}=${shellSingleQuote(value)}`),
        `bash ${WSL_GIT_PROVISION_SCRIPT}`,
      ].join(" ");
      const result = await this.executor.execStream(distroName, ["sh", "-c", command], {
        onData: options.onOutput,
        signal: options.signal,
        timeoutMs: options.timeoutMs ?? 15 * 60_000,
      });
      if (result.exitCode !== 0) {
        const code = parseMarker(result.stdout + "\n" + result.stderr, WSL_GIT_PROVISION_ERROR_PREFIX) ?? "CLONE_FAILED";
        throw Object.assign(
          new Error(`WSL Git workspace provisioning failed for ${context.instance.id}: ${code}.`),
          { code: "GIT_WORKSPACE_PROVISIONING_FAILED", statusCode: 502, details: { code, distroName, instanceId: context.instance.id } },
        );
      }
      context.completeGitWorkspaceProvisioning?.();
      const output = `${result.stdout}\n${result.stderr}`;
      const stages = output.split(/\r?\n/).filter((line) => line.startsWith(WSL_GIT_PROVISION_STAGE_PREFIX)).map((line) => line.slice(WSL_GIT_PROVISION_STAGE_PREFIX.length).trim());
      const commit = parseMarker(output, WSL_GIT_PROVISION_COMMIT_PREFIX);
      this.logger?.("wsl git workspace provisioned", { instanceId: context.instance.id, distroName, stages, ...(commit ? { commit } : {}) });
      return { ...(commit ? { commit } : {}), stages };
    } finally {
      await this.executor.execOrThrow(distroName, ["sh", "-c", `rm -rf ${WSL_GIT_AUTH_DIR}`]).catch(() => undefined);
      fs.rmSync(authDirectory, { recursive: true, force: true });
    }
  }

  private gitEnvironment(context: ExecutorContext): Record<string, string> {
    const input = context.gitWorkspaceProvisioning!;
    const environment: Record<string, string> = {
      TASK_HANDOFF_INSTANCE_ID: context.instance.id,
      TASK_HANDOFF_WORKSPACE: context.project.workspacePolicy.path || WSL_DEFAULT_WORKSPACE,
    };
    for (const [key, value] of workspaceGitEnvironmentEntries({
      url: input.remoteUrl,
      ref: input.ref,
      clone: input.clone,
    }, { legacy: false })) {
      environment[key] = value;
    }
    if (input.clone.subdirectory) environment.TASK_HANDOFF_WORKSPACE_SUBDIRECTORY = input.clone.subdirectory;
    return environment;
  }

  private materializeGitProvisioningAuth(directory: string, input: NonNullable<ExecutorContext["gitWorkspaceProvisioning"]>) {
    const write = (targetDirectory: string, name: string, value: string) => {
      const filePath = path.join(targetDirectory, name);
      fs.writeFileSync(filePath, value, { encoding: "utf8", mode: 0o600 });
      fs.chmodSync(filePath, 0o600);
    };
    input.credentials.forEach((credential, index) => {
      const credentialDirectory = path.join(directory, `credential-${index}`);
      fs.mkdirSync(credentialDirectory, { recursive: true, mode: 0o700 });
      fs.chmodSync(credentialDirectory, 0o700);
      write(credentialDirectory, "scope.json", JSON.stringify(credential.payload.credential.scope));
      if (credential.payload.secret.kind === "https-token") {
        write(credentialDirectory, "username", credential.payload.secret.username);
        write(credentialDirectory, "token", credential.payload.secret.token);
        return;
      }
      write(credentialDirectory, "private-key", credential.payload.secret.privateKey);
      write(credentialDirectory, "known_hosts", credential.payload.secret.pinnedKnownHosts);
      if (credential.payload.secret.passphrase) write(credentialDirectory, "passphrase", credential.payload.secret.passphrase);
    });
  }

  private async bridgeAuth(distroName: string, authDirectory: string) {
    await this.executor.execOrThrow(distroName, ["sh", "-c", `rm -rf ${WSL_GIT_AUTH_DIR} && mkdir -p ${WSL_GIT_AUTH_DIR} && chmod 0700 ${WSL_GIT_AUTH_DIR}`]);
    for (const entry of fs.readdirSync(authDirectory, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        await this.executor.execOrThrow(distroName, ["sh", "-c", `mkdir -p ${WSL_GIT_AUTH_DIR}/${entry.name} && chmod 0700 ${WSL_GIT_AUTH_DIR}/${entry.name}`]);
        for (const file of fs.readdirSync(path.join(authDirectory, entry.name))) {
          await this.executor.copyIntoDistro(distroName, path.join(authDirectory, entry.name, file), `${WSL_GIT_AUTH_DIR}/${entry.name}/${file}`);
        }
        continue;
      }
      await this.executor.copyIntoDistro(distroName, path.join(authDirectory, entry.name), `${WSL_GIT_AUTH_DIR}/${entry.name}`);
    }
    await this.executor.execOrThrow(distroName, ["sh", "-c", `find ${WSL_GIT_AUTH_DIR} -type f -exec chmod 0600 {} +`]);
  }
}

function shellSingleQuote(value: string) {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}
