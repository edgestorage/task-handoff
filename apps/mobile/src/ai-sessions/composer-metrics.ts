import type { AiSessionPermissionMode } from '@task-handoff/protocol/ai-sessions';

export const SESSION_COMPOSER_EXPANDED_RADIUS = 22;
export const SESSION_COMPOSER_COLLAPSED_RADIUS = 28;
export const SESSION_COMPOSER_COLLAPSED_HEIGHT = 56;
export const SESSION_COMPOSER_INPUT_FONT_SIZE = 16;
export const SESSION_COMPOSER_INPUT_LINE_HEIGHT = 23;
export const SESSION_COMPOSER_COLLAPSED_INPUT_PADDING_TOP = 15;
export const SESSION_COMPOSER_COLLAPSED_INPUT_PADDING_BOTTOM = 15;
export const SESSION_COMPOSER_EXPANDED_INPUT_PADDING_TOP = 14;
export const SESSION_COMPOSER_EXPANDED_INPUT_PADDING_BOTTOM = 8;
export const SESSION_COMPOSER_EXPANDED_INPUT_BOTTOM = 50;
export const SESSION_COMPOSER_FOCUSED_MIN_LINES = 2;
export const SESSION_COMPOSER_FOCUSED_MAX_LINES = 4;
export const SESSION_COMPOSER_EXPAND_DURATION_MS = 240;
export const SESSION_COMPOSER_COLLAPSE_DURATION_MS = 180;
export const SESSION_COMPOSER_ACTION_SIZE = 38;
export const SESSION_COMPOSER_ACTION_RADIUS = SESSION_COMPOSER_ACTION_SIZE / 2;
export const SESSION_COMPOSER_ACTION_ICON_SIZE = 17;
export const SESSION_COMPOSER_TOOLBAR_HEIGHT = 56;
export const SESSION_COMPOSER_TOOL_SIZE = 40;
export const SESSION_COMPOSER_ATTACHMENT_ICON_SIZE = 25;
export const SESSION_COMPOSER_MODEL_MAX_WIDTH = 120;
export const SESSION_COMPOSER_TRAILING_TOOL_GAP = 4;
export const SESSION_COMPOSER_COLLAPSED_INPUT_RIGHT = 52;
export const SESSION_COMPOSER_COLLAPSED_INPUT_LEFT = 84;
export const SESSION_COMPOSER_COLLAPSED_INPUT_LEFT_WITHOUT_PERMISSION = 48;
export const SESSION_COMPOSER_PERMISSION_HEIGHT = 38;
export const SESSION_COMPOSER_PERMISSION_RADIUS = SESSION_COMPOSER_PERMISSION_HEIGHT / 2;
export const SESSION_COMPOSER_PERMISSION_ICON_SLOT_SIZE = 20;
export const SESSION_COMPOSER_PERMISSION_ICON_LEFT = 8;
export const SESSION_COMPOSER_PERMISSION_TEXT_LEFT = 34;
export const SESSION_COMPOSER_PERMISSION_TEXT_RIGHT = 24;
export const SESSION_COMPOSER_PERMISSION_CHEVRON_RIGHT = 8;
export const SESSION_COMPOSER_PERMISSION_CHEVRON_SIZE = 10;
export const SESSION_COMPOSER_PERMISSION_WIDTH_OVERHEAD = 58;
export const SESSION_COMPOSER_PERMISSION_COLLAPSED_WIDTH = 36;

const SESSION_COMPOSER_EXPANDED_INPUT_VERTICAL_PADDING = SESSION_COMPOSER_EXPANDED_INPUT_PADDING_TOP
  + SESSION_COMPOSER_EXPANDED_INPUT_PADDING_BOTTOM;

export const SESSION_COMPOSER_FOCUSED_MIN_HEIGHT = SESSION_COMPOSER_EXPANDED_INPUT_BOTTOM
  + SESSION_COMPOSER_EXPANDED_INPUT_VERTICAL_PADDING
  + SESSION_COMPOSER_FOCUSED_MIN_LINES * SESSION_COMPOSER_INPUT_LINE_HEIGHT;
export const SESSION_COMPOSER_FOCUSED_MAX_HEIGHT = SESSION_COMPOSER_EXPANDED_INPUT_BOTTOM
  + SESSION_COMPOSER_EXPANDED_INPUT_VERTICAL_PADDING
  + SESSION_COMPOSER_FOCUSED_MAX_LINES * SESSION_COMPOSER_INPUT_LINE_HEIGHT;

export function sessionComposerCollapsedInputRight(modelControlsVisible: boolean) {
  return SESSION_COMPOSER_COLLAPSED_INPUT_RIGHT
    + (modelControlsVisible ? SESSION_COMPOSER_MODEL_MAX_WIDTH + SESSION_COMPOSER_TRAILING_TOOL_GAP : 0);
}

export function sessionComposerExpandedHeightForContentSize(contentSizeHeight: number) {
  const measuredHeight = Number.isFinite(contentSizeHeight) ? Math.max(0, contentSizeHeight) : 0;
  const textHeight = Math.max(
    0,
    measuredHeight - SESSION_COMPOSER_COLLAPSED_INPUT_PADDING_TOP - SESSION_COMPOSER_COLLAPSED_INPUT_PADDING_BOTTOM,
  );
  const lineCount = Math.max(
    SESSION_COMPOSER_FOCUSED_MIN_LINES,
    Math.min(SESSION_COMPOSER_FOCUSED_MAX_LINES, Math.ceil(textHeight / SESSION_COMPOSER_INPUT_LINE_HEIGHT)),
  );
  return SESSION_COMPOSER_EXPANDED_INPUT_BOTTOM
    + SESSION_COMPOSER_EXPANDED_INPUT_VERTICAL_PADDING
    + lineCount * SESSION_COMPOSER_INPUT_LINE_HEIGHT;
}

export function sessionComposerPermissionIconSize(mode: AiSessionPermissionMode) {
  return mode === 'ask' ? 21 : 22;
}
